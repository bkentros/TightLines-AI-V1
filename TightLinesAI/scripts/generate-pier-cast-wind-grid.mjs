import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const sourcePath = resolve(root, "assets/data/pier-cast-great-lakes-map.json");
const outputPath = resolve(root, "lib/pierCastWindGrid.generated.ts");
const sourceText = readFileSync(sourcePath, "utf8");
const geometry = JSON.parse(sourceText);
const spacing = 0.4;

const lakeIds = new Map([
  ["Lake Superior", "superior"],
  ["Lake Michigan", "michigan"],
  ["Lake Huron", "huron"],
  ["Lake Erie", "erie"],
  ["Lake Ontario", "ontario"],
]);

function polygonRings(feature) {
  if (feature.geometry.type === "Polygon") return feature.geometry.coordinates;
  if (feature.geometry.type === "MultiPolygon") {
    return feature.geometry.coordinates.flatMap((polygon) => [polygon]);
  }
  throw new Error(`Unsupported lake geometry: ${feature.geometry.type}`);
}

function pointInRing([x, y], ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    const crosses = yi > y !== yj > y &&
      x < ((xj - xi) * (y - yi)) / (yj - yi) + xi;
    if (crosses) inside = !inside;
  }
  return inside;
}

function pointInPolygon(point, rings) {
  if (!pointInRing(point, rings[0])) return false;
  return !rings.slice(1).some((hole) => pointInRing(point, hole));
}

function pointInFeature(point, feature) {
  if (feature.geometry.type === "Polygon") {
    return pointInPolygon(point, feature.geometry.coordinates);
  }
  return feature.geometry.coordinates.some((polygon) =>
    pointInPolygon(point, polygon)
  );
}

function bounds(feature) {
  const coordinates = polygonRings(feature).flat(3);
  const xs = [];
  const ys = [];
  const walk = (value) => {
    if (Array.isArray(value) && value.length === 2 && value.every(Number.isFinite)) {
      xs.push(value[0]);
      ys.push(value[1]);
      return;
    }
    if (Array.isArray(value)) value.forEach(walk);
  };
  walk(feature.geometry.coordinates);
  return [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
}

const nodes = [];
for (const feature of geometry.lakes.features) {
  const lakeId = lakeIds.get(feature.properties.name);
  if (!lakeId) throw new Error(`Unknown Great Lake: ${feature.properties.name}`);
  const [west, south, east, north] = bounds(feature);
  let index = 0;
  const firstLatitude = Math.ceil(south / spacing) * spacing;
  const firstLongitude = Math.ceil(west / spacing) * spacing;
  for (let latitude = firstLatitude; latitude <= north; latitude += spacing) {
    for (let longitude = firstLongitude; longitude <= east; longitude += spacing) {
      const point = [Number(longitude.toFixed(4)), Number(latitude.toFixed(4))];
      if (!pointInFeature(point, feature)) continue;
      nodes.push({
        nodeId: `${lakeId}_${String(index).padStart(3, "0")}`,
        lakeId,
        latitude: point[1],
        longitude: point[0],
      });
      index += 1;
    }
  }
  if (index < 3) throw new Error(`${feature.properties.name} wind grid is too sparse.`);
}

const sourceSha256 = createHash("sha256").update(sourceText).digest("hex");
const output = `// Generated by scripts/generate-pier-cast-wind-grid.mjs. Do not edit by hand.\n` +
  `import type { PierCastGreatLakeId } from "./pierCastGreatLakes.ts";\n\n` +
  `export type PierCastWindGridNode = {\n` +
  `  nodeId: string;\n  lakeId: PierCastGreatLakeId;\n  latitude: number;\n  longitude: number;\n};\n\n` +
  `export const PIER_CAST_WIND_GRID_SPACING_DEGREES = ${spacing} as const;\n` +
  `export const PIER_CAST_WIND_GRID_SOURCE_SHA256 = "${sourceSha256}" as const;\n` +
  `export const PIER_CAST_WIND_GRID = Object.freeze(${JSON.stringify(nodes, null, 2)}) satisfies readonly PierCastWindGridNode[];\n`;

writeFileSync(outputPath, output);
execFileSync("deno", ["fmt", outputPath], { stdio: "ignore" });
console.log(JSON.stringify({ outputPath, nodeCount: nodes.length, spacing }, null, 2));
