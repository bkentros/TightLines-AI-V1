type RiverDefinition = {
  id: "milwaukee" | "sheboygan" | "root";
  siteId: string;
  startYear: number;
  endYear: number;
  targetEndMonthDay: string;
};

type DailyValue = { localDate: string; value: number };
type GeneratedNormal = {
  average: number;
  p10: number;
  p25: number;
  median: number;
  p75: number;
  p90: number;
  historicalYears: number;
  sampleCount: number;
  availableWindowDays: number;
  windowStartMonthDay: string;
  windowEndMonthDay: string;
};

