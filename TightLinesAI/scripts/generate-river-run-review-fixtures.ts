function reviewRecentDailyPushReads(localDate: string) {
  const examples = [
    { score: null, label: "No supportive window", slot: null },
    { score: null, label: "No supportive window", slot: null },
    { score: 63, label: "Possible", slot: "08:00" },
    { score: null, label: "No supportive window", slot: null },
    { score: 81, label: "Strong", slot: "20:00" },
    { score: 63, label: "Possible", slot: "16:00" },
    { score: null, label: "No supportive window", slot: null },
  ];
  const reads = [];
  for (let dayOffset = 1; dayOffset <= 7; dayOffset += 1) {
    const readDate = addDays(localDate, -dayOffset);
    if (readDate < reviewWindow.startDate) break;
    const example = examples[dayOffset - 1];
    reads.push(
      example.slot
        ? {
          localDate: readDate,
          status: "supportive_window" as const,
          refreshSlot: example.slot,
          conditionRefreshAt: `${readDate}T23:59:00.000Z`,
          score: example.score,
          label: example.label,
        }
        : {
          localDate: readDate,
          status: "no_supportive_window" as const,
          score: null,
          label: "No supportive window" as const,
        },
    );
  }
  return reads;
}

function insufficientConditionCases(target: ConditionsSuggestCheckpoint) {
  const fullEvidence = cumulativeEvidence(target, "typical");
  const cutoff = target.cutoffDate;
  const sparseEvidence: ConditionsSuggestEvidenceByDate = {};
  for (let index = 0; index < 3; index += 1) {
    const localDate = addDays(target.observationStartDate, index);
    sparseEvidence[localDate] = fullEvidence[localDate];
  }
  sparseEvidence[cutoff] = fullEvidence[cutoff];
  return [
    ["missing_baseline", "Insufficient · no historical baseline", []],
    [
      "few_years",
      "Insufficient · fewer than five years",
      [baseline(target, { distinctYears: 4 })],
    ],
    [
      "version_mismatch",
      "Insufficient · baseline version mismatch",
      [baseline(target, { baselineVersion: "old-version" })],
    ],
    [
      "window_mismatch",
      "Insufficient · window mismatch",
      [baseline(target, { expectedDays: baseline(target).expectedDays + 1 })],
    ],
    [
      "missing_gauge",
      "Insufficient · checkpoint gauge missing",
      [baseline(target)],
    ],
    [
      "missing_temperature",
      "Insufficient · checkpoint temperature missing",
      [baseline(target)],
    ],
    [
      "source_mismatch",
      "Insufficient · source mismatch",
      [baseline(target)],
    ],
    [
      "limited_days",
      "Insufficient · limited matching days",
      [baseline(target)],
    ],
  ].map(([id, label, baselines]) => ({
    id: id as string,
    label: label as string,
    localDate: target.checkpointDate,
    make: () => {
      let evidenceByDate = fullEvidence;
      if (id === "missing_gauge") {
        evidenceByDate = {
          ...fullEvidence,
          [cutoff]: {
            "16:00": evidence(600, 60, { gaugeFreshness: "missing" }),
          },
        };
      }
      if (id === "missing_temperature") {
        evidenceByDate = {
          ...fullEvidence,
          [cutoff]: {
            "16:00": evidence(600, 60, {
              waterTemperatureFreshness: "missing",
              waterTempF: null,
            }),
          },
        };
      }
      if (id === "source_mismatch") {
        evidenceByDate = {
          ...fullEvidence,
          [cutoff]: {
            "16:00": evidence(600, 60, {
              waterTemperatureSourceId: "other-source",
            }),
          },
        };
      }
      if (id === "limited_days") evidenceByDate = sparseEvidence;
      return scoreConditionsSuggest({
        localDate: target.checkpointDate,
        run,
        evidenceByDate,
        baselines: baselines as RiverRunConditionsSuggestBaseline[],
      });
    },
  }));
}

function conditionResult(
  label: "Typical" | "Delayed",
): RiverRunConditionsSuggest {
  const target = label === "Delayed"
    ? checkpoint("peak_start")
    : checkpoint("building_start");
  return scoreConditionsSuggest({
    localDate: target.checkpointDate,
    run,
    evidenceByDate: cumulativeEvidence(
      target,
      label === "Delayed" ? "delayed" : "typical",
    ),
    baselines: checkpoints
      .filter((item) => item.checkpointDate <= target.checkpointDate)
      .map((item) => baseline(item)),
  });
}

function typicalConditionResultForDate(
  localDate: string,
): RiverRunConditionsSuggest {
  const state = resolveConditionsSuggestCheckpointState(run, localDate);
  const target = state.activeCheckpoint;
  if (!target) {
    return scoreConditionsSuggest({
      localDate,
      run,
      evidenceByDate: {},
      baselines: [],
    });
  }
  return scoreConditionsSuggest({
    localDate,
    run,
    evidenceByDate: cumulativeEvidence(target, "typical"),
    baselines: checkpoints
      .filter((item) => item.checkpointDate <= target.checkpointDate)
      .map((item) => baseline(item)),
  });
}

function reviewTrackingState(localDate: string) {
  if (localDate < reviewWindow.startDate) return "not_started" as const;
  if (localDate > reviewWindow.endDate) return "complete" as const;
  return "active" as const;
}

