function cumulativeEvidence(
  target: ConditionsSuggestCheckpoint,
  kind: "ahead" | "typical" | "delayed",
): ConditionsSuggestEvidenceByDate {
  const count = daysBetween(
    target.observationStartDate,
    target.cutoffDate,
  ) + 1;
  const result: ConditionsSuggestEvidenceByDate = {};
  for (let index = 0; index < count; index += 1) {
    const localDate = addDays(target.observationStartDate, index);
    const progress = count <= 1 ? 1 : index / (count - 1);
    const gaugeValue = kind === "ahead"
      ? 300 + progress * 900
      : kind === "delayed"
      ? 500
      : 500 + index * 20;
    const waterTempF = kind === "ahead"
      ? 70 - progress * 20
      : kind === "delayed"
      ? 70
      : 64 - index * 0.4;
    result[localDate] = {
      "16:00": evidence(gaugeValue, waterTempF),
    };
  }
  return result;
}

function mixedEvidence(
  target: ConditionsSuggestCheckpoint,
): ConditionsSuggestEvidenceByDate {
  const result = cumulativeEvidence(target, "ahead");
  for (const date of Object.keys(result)) {
    const current = result[date]["16:00"]!;
    result[date] = {
      "16:00": { ...current, waterTempF: 70 },
    };
  }
  return result;
}

function scenarioCount(value: Group[]): number {
  return value.reduce((total, group) => total + group.scenarios.length, 0);
}

function shallowSnapshotDiff(
  base: RiverRunSnapshotResponse,
  target: RiverRunSnapshotResponse,
): Partial<RiverRunSnapshotResponse> {
  const diff: Partial<RiverRunSnapshotResponse> = {};
  for (
    const key of Object.keys(target) as Array<keyof RiverRunSnapshotResponse>
  ) {
    if (JSON.stringify(base[key]) === JSON.stringify(target[key])) continue;
    (diff as Record<string, unknown>)[key] = target[key];
  }
  return diff;
}

function title(value: string): string {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

function slug(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(
    /^_|_$/g,
    "",
  );
}
