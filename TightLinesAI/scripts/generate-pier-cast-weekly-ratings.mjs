import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");
const sourcePath = path.join(
  repoRoot,
  "docs/PierCast_Core_Species_Seasonal_Curves.json",
);
const outputPath = path.join(
  repoRoot,
  "docs/PierCast_Core_Species_Weekly_Ratings.csv",
);
const engineOutputPath = path.join(
  repoRoot,
  "supabase/functions/_shared/pierCastEngine/config/coreSeasonal.generated.ts",
);

const source = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const referenceYear = 2025;

function dayOfYear(monthDay) {
  const [month, day] = monthDay.split("-").map(Number);
  const date = new Date(Date.UTC(referenceYear, month - 1, day));
  if (
    date.getUTCFullYear() !== referenceYear ||
    date.getUTCMonth() !== month - 1 ||
    date.getUTCDate() !== day
  ) {
    throw new Error(`Invalid month-day: ${monthDay}`);
  }
  return Math.floor((date - Date.UTC(referenceYear, 0, 1)) / 86400000);
}

function monthDay(dayIndex) {
  const date = new Date(Date.UTC(referenceYear, 0, 1 + dayIndex));
  return `${String(date.getUTCMonth() + 1).padStart(2, "0")}-${
    String(date.getUTCDate()).padStart(2, "0")
  }`;
}

function evaluate(knots, targetDay) {
  const ordered = knots
    .map((knot) => ({ ...knot, day: dayOfYear(knot.monthDay) }))
    .sort((left, right) => left.day - right.day);
  const duplicate = ordered.find(
    (knot, index) => index > 0 && knot.day === ordered[index - 1].day,
  );
  if (duplicate) throw new Error(`Duplicate knot: ${duplicate.monthDay}`);
  for (const knot of ordered) {
    if (!Number.isFinite(knot.rating) || knot.rating < 1 || knot.rating > 10) {
      throw new Error(`Invalid rating at ${knot.monthDay}`);
    }
  }

  const exact = ordered.find((knot) => knot.day === targetDay);
  if (exact) return exact.rating;
  const before = [...ordered].reverse().find((knot) => knot.day < targetDay) ??
    {
      ...ordered.at(-1),
      day: ordered.at(-1).day - 365,
    };
  const after = ordered.find((knot) => knot.day > targetDay) ?? {
    ...ordered[0],
    day: ordered[0].day + 365,
  };
  const progress = (targetDay - before.day) / (after.day - before.day);
  return before.rating + (after.rating - before.rating) * progress;
}

if (source.curves.length !== 20) {
  throw new Error(`Expected 20 core curves, found ${source.curves.length}`);
}

const uniquePairs = new Set();
for (const curve of source.curves) {
  const key = `${curve.cityId}|${curve.speciesId}`;
  if (uniquePairs.has(key)) throw new Error(`Duplicate curve pair: ${key}`);
  uniquePairs.add(key);
}

const columns = [
  "research_version",
  "curve_id",
  "city_id",
  "species_id",
  "week",
  "week_start_mm_dd",
  "week_midpoint_mm_dd",
  "seasonal_opportunity_ceiling",
  "one_decimal_display_preview",
  "confidence",
  "production_ready",
];
const rows = [columns.join(",")];

for (const curve of source.curves) {
  for (let week = 1; week <= 52; week += 1) {
    const startDay = (week - 1) * 7;
    const midpointDay = startDay + 3;
    const rating = evaluate(curve.knots, midpointDay);
    const values = [
      source.researchVersion,
      curve.curveId,
      curve.cityId,
      curve.speciesId,
      week,
      monthDay(startDay),
      monthDay(midpointDay),
      rating.toFixed(1),
      `${rating.toFixed(1)}/10`,
      curve.confidence,
      false,
    ];
    rows.push(values.join(","));
  }
}

fs.writeFileSync(outputPath, `${rows.join("\n")}\n`);
const engineCurves = source.curves.map((curve) => ({
  curveId: curve.curveId,
  cityId: curve.cityId,
  speciesId: curve.speciesId,
  calibrationStatus: "provisional",
  knots: curve.knots.map(({ monthDay, rating }) => ({ monthDay, rating })),
}));
const generated =
  `// Generated by scripts/generate-pier-cast-weekly-ratings.mjs.
// Source of truth: docs/PierCast_Core_Species_Seasonal_Curves.json.
// Do not hand-edit.
import type {
  PierCastCityId,
  PierCastSeasonalOpportunityCurve,
  PierCastSpeciesId,
} from "../types.ts";

export type PierCastCoreSeasonalCurve = PierCastSeasonalOpportunityCurve & {
  cityId: PierCastCityId;
  speciesId: PierCastSpeciesId;
};

export const PIER_CAST_CORE_SEASONAL_CURVES = ${
    JSON.stringify(engineCurves, null, 2)
  } as const satisfies readonly PierCastCoreSeasonalCurve[];
`;
fs.writeFileSync(engineOutputPath, generated);
execFileSync("deno", ["fmt", engineOutputPath], { stdio: "inherit" });
console.log(`Wrote ${rows.length - 1} weekly rows to ${outputPath}`);
console.log(
  `Wrote ${engineCurves.length} engine curves to ${engineOutputPath}`,
);
