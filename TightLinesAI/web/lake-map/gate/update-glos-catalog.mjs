/**
 * Builds the small metadata catalog used to join GLOS's bulk latest feed.
 *
 * The public API returns ~5.5 MB of dataset/parameter metadata. Parsing that on
 * every Cloudflare edge would waste CPU, so this script reduces it to only the
 * Great Lakes platforms and temperature parameters needed by the gatekeeper.
 * Run: npm run refresh:glos-catalog
 */
import fs from 'node:fs';

const DATASETS_URL = 'https://seagull-api.glos.org/api/v1/obs-datasets.geojson';
const PARAMETERS_URL = 'https://seagull-api.glos.org/api/v1/parameters';
const OUTPUT = new URL('./glos-catalog.js', import.meta.url);
const TEMP_NAMES = new Set(['sea_surface_temperature', 'sea_water_temperature']);
const BOX = { west: -92.6, east: -75.6, south: 41.0, north: 49.4 };

async function json(url) {
  const response = await fetch(url, { headers: { 'user-agent': 'PierCast-LakeMap-Catalog/1.0 (+https://finfindr.app)' } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}

const [featureCollection, parameters] = await Promise.all([json(DATASETS_URL), json(PARAMETERS_URL)]);
const datasets = {};
for (const feature of featureCollection.features || []) {
  const [lon, lat] = feature.geometry?.coordinates || [];
  const props = feature.properties || {};
  if (!Number.isFinite(lon) || !Number.isFinite(lat) || lon < BOX.west || lon > BOX.east || lat < BOX.south || lat > BOX.north) continue;
  if (!(props.parameters || []).some((item) => TEMP_NAMES.has(item.standard_name))) continue;
  datasets[props.obs_dataset_id] = {
    externalId: props.org_platform_id || null,
    name: props.platform_name || `GLOS station ${props.obs_dataset_id}`,
    body: props.body_of_water || null,
    type: props.platform_type || null,
    lon,
    lat,
  };
}

const temperatureParameters = {};
for (const parameter of parameters) {
  if (!TEMP_NAMES.has(parameter.standard_name) || parameter.public === false || parameter.hide_in_ui === true) continue;
  temperatureParameters[parameter.parameter_id] = {
    standard: parameter.standard_name,
    name: parameter.parameter_name || parameter.standard_name,
    depthM: Number.isFinite(parameter.depth) ? parameter.depth : null,
  };
}

const generatedAt = new Date().toISOString();
const moduleText = `/** Generated by update-glos-catalog.mjs from the public GLOS Seagull API. */\n` +
  `export const GLOS_CATALOG_GENERATED_AT=${JSON.stringify(generatedAt)};\n` +
  `export const GLOS_DATASETS=${JSON.stringify(datasets)};\n` +
  `export const GLOS_TEMP_PARAMETERS=${JSON.stringify(temperatureParameters)};\n`;
fs.writeFileSync(OUTPUT, moduleText);
console.log(`wrote ${Object.keys(datasets).length} Great Lakes datasets and ${Object.keys(temperatureParameters).length} temperature parameters`);
